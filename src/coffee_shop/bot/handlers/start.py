from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message


router = Router()

@router.message(Command("start"))
async def start_handler(message: Message) -> None:
    await message.answer(f"""
☕ **Добро пожаловать в нашу кофейню, {message.from_user.username}!**

Рады видеть тебя! 

Я — виртуальный помощник нашей кофейни. Готов ответить на твои вопросы и помочь разобраться во всём, что касается нашего заведения.

Можешь спросить меня о чём угодно:
- ☕ Нашем меню и ассортименте;
- 🥐 Напитках, десертах и ингредиентах;
- 📍 Адресе и расположении кофейни;
- 🕒 Графике работы;
- 💳 Способах оплаты и других условиях;
- 💬 Любых других вопросах, связанных с кофейней.

**Просто напиши свой вопрос обычным сообщением — команды не нужны!**

Если я не смогу помочь с ответом, подскажу, как связаться с нашим менеджером.

Хорошего дня и приятного общения! ❤️
""")


@router.message(Command("help"))
async def help_handler(message: Message) -> None:
    await message.answer("""
ℹ️ **Как пользоваться ботом?**

Всё очень просто! Я работаю на основе искусственного интеллекта и умею отвечать на вопросы о нашей кофейне.

**Как задать вопрос?**

Просто отправь мне сообщение в Telegram. Например:

☕ «Какие у вас есть виды кофе?»

🥛 «Есть ли у вас безлактозное молоко?»

🕒 «До скольки вы сегодня работаете?»

📍 «Где вы находитесь?»

🥐 «Какие десерты есть в меню?»

**Что делать, если бот не знает ответа?**

Ничего страшного! Если я не смогу достоверно ответить на твой вопрос, предложу связаться с менеджером кофейни по телефону.

Приятного общения и хорошего настроения! ☕
""")